#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const args = Object.fromEntries(
  process.argv
    .slice(2)
    .map((arg, index, all) => (arg.startsWith('--') ? [arg.slice(2), all[index + 1]] : ['', '']))
);

if (!args.input || !args.output) {
  console.error(
    'Usage: node scripts/transform-supabase-auth.mjs --input <restricted-export.json> --output <import.sql>'
  );
  process.exit(2);
}

const input = JSON.parse(await readFile(args.input, 'utf8'));
if (!Array.isArray(input.users) || !Array.isArray(input.identities)) {
  throw new Error('Input must contain users[] and identities[]');
}

const text = (value, field) => {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing ${field}`);
  return value;
};
const sql = (value) => (value == null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);
const epochMillis = (value, field) => {
  const date = new Date(text(value, field));
  if (Number.isNaN(date.valueOf())) throw new Error(`Invalid ${field}`);
  return date.valueOf();
};
const normalizedEmail = (value) => text(value, 'email').trim().toLowerCase();

const ids = new Set();
const emails = new Set();
const identitiesByUser = new Map();
for (const identity of input.identities) {
  const userId = text(identity.user_id, 'identity.user_id');
  const provider = text(identity.provider, 'identity.provider').toLowerCase();
  const key = `${provider}:${text(identity.id, 'identity.id')}`;
  if (identitiesByUser.get(userId)?.some((item) => item.key === key)) {
    throw new Error('Duplicate identity record');
  }
  identitiesByUser.set(userId, [...(identitiesByUser.get(userId) ?? []), { key, provider }]);
}

const users = [...input.users].sort((a, b) => String(a.id).localeCompare(String(b.id)));
const rows = [];
const counts = { credential: 0, password_setup: 0, verified: 0, unverified: 0 };
for (const user of users) {
  const id = text(user.id, 'user.id');
  const email = normalizedEmail(user.email);
  if (ids.has(id)) throw new Error('Duplicate user ID');
  if (emails.has(email)) throw new Error('Duplicate normalized email');
  ids.add(id);
  emails.add(email);

  if (user.deleted_at || user.banned_until || user.is_anonymous || (user.phone && !user.email)) {
    throw new Error('Unsupported deleted, banned, anonymous, or phone-only record');
  }
  const providers = new Set((identitiesByUser.get(id) ?? []).map(({ provider }) => provider));
  const disposition = user.migration_disposition ?? null;
  const hash = user.encrypted_password || null;
  const bcrypt = typeof hash === 'string' && /^\$2[aby]\$\d\d\$/.test(hash);
  const hasOauth = [...providers].some((provider) => provider !== 'email');
  if (hasOauth && disposition !== 'password_setup') {
    throw new Error('OAuth identity requires migration_disposition=password_setup');
  }
  if (hash && !bcrypt) throw new Error('Unsupported credential hash format');
  if (!bcrypt && disposition !== 'password_setup') {
    throw new Error(
      'User without a supported credential requires migration_disposition=password_setup'
    );
  }

  const created = epochMillis(user.created_at, 'created_at');
  const updated = epochMillis(user.updated_at ?? user.created_at, 'updated_at');
  const verified = Boolean(user.email_confirmed_at);
  const metadata =
    user.raw_user_meta_data && typeof user.raw_user_meta_data === 'object'
      ? user.raw_user_meta_data
      : {};
  const name = String(metadata.name ?? metadata.full_name ?? user.email).trim();
  rows.push(
    `INSERT INTO auth_users (id, name, email, emailVerified, image, createdAt, updatedAt) VALUES (${sql(id)}, ${sql(name)}, ${sql(email)}, ${verified ? 1 : 0}, NULL, ${created}, ${updated});`
  );
  counts[verified ? 'verified' : 'unverified']++;
  if (bcrypt && disposition !== 'password_setup') {
    rows.push(
      `INSERT INTO auth_accounts (id, accountId, providerId, userId, password, createdAt, updatedAt) VALUES (${sql(`credential:${id}`)}, ${sql(id)}, 'credential', ${sql(id)}, ${sql(hash)}, ${created}, ${updated});`
    );
    counts.credential++;
  } else {
    counts.password_setup++;
  }
}

for (const userId of identitiesByUser.keys()) {
  if (!ids.has(userId)) throw new Error('Orphan identity record');
}

const body = [
  '-- Generated by transform-supabase-auth.mjs. Contains password hashes; keep encrypted and out of Git.',
  '-- D1 owns transaction boundaries; this file intentionally contains plain INSERT statements only.',
  ...rows,
  '',
].join('\n');
await writeFile(args.output, body, { mode: 0o600, flag: 'wx' });
const checksum = createHash('sha256').update(body).digest('hex');
console.log(JSON.stringify({ users: users.length, ...counts, sha256: checksum }));
